CREATE OR REPLACE PACKAGE BODY PKG_STOCK AS

  -- 在庫の変動を受注DBの履歴に反映（DBリンク越しの更新）
  PROCEDURE SYNC_TO_ORDER(p_item_id IN VARCHAR2) IS
  BEGIN
    INSERT INTO ORDER_STOCK_HIST@ORDERDB (ITEM_ID, QTY, SYNCED_AT)
      SELECT ITEM_ID, QTY, SYSDATE FROM STOCK WHERE ITEM_ID = p_item_id;
  END SYNC_TO_ORDER;

END PKG_STOCK;
/
