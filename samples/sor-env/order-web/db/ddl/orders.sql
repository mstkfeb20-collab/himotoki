CREATE TABLE ORDERS (
  ORDER_ID     VARCHAR2(12) NOT NULL,
  CUSTOMER_ID  VARCHAR2(10) NOT NULL,
  STATUS       VARCHAR2(12) NOT NULL,
  SHIP_STATUS  VARCHAR2(12),
  NOTE         VARCHAR2(200),
  ORDERED_AT   DATE NOT NULL,
  CONSTRAINT PK_ORDERS PRIMARY KEY (ORDER_ID)
);
COMMENT ON COLUMN ORDERS.NOTE IS '備考';

CREATE TABLE ORDER_ITEMS (
  ORDER_ID VARCHAR2(12) NOT NULL,
  ITEM_ID  VARCHAR2(10) NOT NULL,
  QTY      NUMBER(5) NOT NULL
);

CREATE TABLE AUDIT_LOG (
  ORDER_ID  VARCHAR2(12),
  EVENT     VARCHAR2(20),
  LOGGED_AT DATE
);

CREATE TABLE ORDER_STOCK_HIST (
  ITEM_ID   VARCHAR2(10),
  QTY       NUMBER(7),
  SYNCED_AT DATE
);

CREATE TABLE ORDER_SHIP_RESULT (
  ORDER_ID   VARCHAR2(12),
  SHIPPED_AT DATE,
  CARRIER    VARCHAR2(20)
);

CREATE SEQUENCE ORDER_SEQ;
