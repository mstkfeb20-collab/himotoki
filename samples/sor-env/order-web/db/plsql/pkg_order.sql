CREATE OR REPLACE PACKAGE BODY PKG_ORDER AS

  -- 受注確定。行ロックを取ってから確定し、自分でコミットする
  PROCEDURE CONFIRM_ORDER(p_order_id IN VARCHAR2) IS
    v_status ORDERS.STATUS%TYPE;
  BEGIN
    SELECT STATUS INTO v_status FROM ORDERS WHERE ORDER_ID = p_order_id FOR UPDATE;
    UPDATE ORDERS SET STATUS = 'CONFIRMED' WHERE ORDER_ID = p_order_id;
    LOG_STATUS(p_order_id, 'CONFIRMED');
    COMMIT;
  END CONFIRM_ORDER;

  -- 状態の記録。呼び出し元のトランザクションとは独立
  PROCEDURE LOG_STATUS(p_order_id IN VARCHAR2, p_event IN VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    INSERT INTO AUDIT_LOG (ORDER_ID, EVENT, LOGGED_AT) VALUES (p_order_id, p_event, SYSDATE);
    COMMIT;
  END LOG_STATUS;

  -- 古い監査ログの削除（1000 件ずつコミット）
  PROCEDURE PURGE_AUDIT(p_days IN NUMBER) IS
  BEGIN
    LOOP
      DELETE FROM AUDIT_LOG WHERE LOGGED_AT < SYSDATE - p_days AND ROWNUM <= 1000;
      EXIT WHEN SQL%ROWCOUNT = 0;
      COMMIT;
    END LOOP;
  END PURGE_AUDIT;

END PKG_ORDER;
/
